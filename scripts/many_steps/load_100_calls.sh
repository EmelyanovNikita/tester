#!/bin/sh
# Нагрузочный тест: 100 одновременных звонков из call_rtp.txt, у каждого настоящий RTP на обеих ногах.
# Звонки стартуют по 20 в секунду (весь набор поднимается за ~5 с), каждый длится ~12 с,
# поэтому около 100 звонков идут одновременно. В конце тестер печатает сводку: успешные и проваленные звонки,
# длительности, потери и джиттер по всем RTP-потокам, список ошибок.
#
# Использование: ./scripts/many_steps/load_100_calls.sh [config/config.json] [дополнительные флаги тестера, например --verbose]
# В config.json: "rtp": {"ip": "<адрес тестера>", "port_min": 20000, "port_max": 30000} — нужно 200 портов (по два на звонок).
cd "$(dirname "$0")/../.." || exit 1
CONFIG="${1:-config/config.json}"
[ $# -gt 0 ] && shift

exec go run ./cmd/tester -p "$CONFIG" -s scripts/many_steps/call_rtp.txt --parallel 100 --rate 20 "$@"
